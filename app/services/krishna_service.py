from langchain_core.prompts import ChatPromptTemplate
from langchain_groq import ChatGroq
from langchain_core.output_parsers import StrOutputParser
from dotenv import load_dotenv
from pydantic import BaseModel, Field

from app.services.retrieval_service import retrieve_krishna_knowledge

load_dotenv()



class KrishnaResponse(BaseModel):
    """Defines the structured response generated by KrishnaAI."""

    guidance: str = Field(
        description="Compassionate and practical guidance for the user's dilemma."
    )

    story_title: str = Field(
        description="Title of the most relevant retrieved Krishna story."
    )

    story_explanation: str = Field(
        description="Faithful explanation using only the retrieved story."
    )

    practical_connection: str = Field(
        description="How the retrieved story's teaching relates to the user's dilemma."
    )

    reflection: str = Field(
        description="One short, original reflection inspired by the discussion."
    )

    used_source_ids: list[str] = Field(
        description="IDs of retrieved stories actually used in the response."
    )



def get_krishna_response(question: str):

    # 1. Retrieve relevant stories
    documents = retrieve_krishna_knowledge(question)

    # 2. Fallback if no knowledge is retrieved
    if not documents:
        return {
            "answer": (
                "I don't have sufficient knowledge in my "
                "current knowledge base to guide you on this dilemma."
            ),
            "sources": []
        }

    # 3. Prepare retrieved context
    
    context = "\n\n".join(
        f"""
    Source ID: {doc.metadata.get('id')}
    Story Title: {doc.metadata.get('title')}

    {doc.page_content}
    """
        for doc in documents
    )

    # 4. Krishna's personality and response structure
    prompt = ChatPromptTemplate.from_messages([
        (
            "system",
            
"""
You are KrishnaAI, a thoughtful and compassionate guide
inspired by the teachings and personality of Lord Krishna.

Your purpose is to help users reflect on their personal
dilemmas using the provided knowledge base.

PERSONALITY:
- Speak calmly, wisely and compassionately.
- Never judge or shame the user.
- Give practical and thoughtful guidance.
- Help users think independently.
- Never claim to be the actual Lord Krishna.

KNOWLEDGE AND ACCURACY RULES:

1. Use the retrieved context as the only source
   for stories and their teachings.

2. Never invent story events, conversations,
   character motivations or scripture references.

3. Explain retrieved stories faithfully.
   Do not add details that are absent from the context.

4. Clearly distinguish between:
   - Information from retrieved stories.
   - Your own practical interpretation or advice.

5. General life advice is allowed, but never falsely
   attribute it to Krishna or any scripture.

6. Never create fake scripture quotations or verses.

7. If no relevant knowledge is retrieved,
   return the fallback response.

8. Mention only sources that genuinely support
   the story or teaching discussed.

9. Every retrieved story has a Source ID.

10. When you use a retrieved story, include its exact
    Source ID in used_source_ids.

11. Never invent or modify Source IDs.

12. If you do not use a retrieved story,
    return an empty used_source_ids list.

RESPONSE STRUCTURE:


1. KRISHNA'S GUIDANCE:
Understand the user's dilemma and provide
compassionate, practical guidance.

2. A STORY TO REFLECT UPON:
Select the most relevant retrieved story.
Explain only the events and teaching present
in the retrieved context.
Connect its teaching to the user's situation.

3. A FINAL REFLECTION:
Write one short, original reflection inspired
by the discussion.
Never present it as an authentic scripture quotation.

Keep the response natural, meaningful and concise.

RETRIEVED KNOWLEDGE:
{context}
"""

        ),
        ("human", "{question}")
    ])

    # 5. Initialize Groq
    llm = ChatGroq(
        model_name="openai/gpt-oss-20b",
        temperature=0,
        max_tokens=1500
    )

   
    # 6. Configure structured output
    structured_llm = llm.with_structured_output(KrishnaResponse)

    # 7. Build and execute chain
    chain = prompt | structured_llm

    response = chain.invoke({
        "context": context,
        "question": question
    })

    
    # 8. Validate selected source IDs
    retrieved_documents = {
        doc.metadata["id"]: doc
        for doc in documents
    }

    valid_source_ids = []

    for source_id in response.used_source_ids:

        if source_id in retrieved_documents:
            if source_id not in valid_source_ids:
                valid_source_ids.append(source_id)


    # 9. Build verified source list
    sources = []

    for source_id in valid_source_ids:

        doc = retrieved_documents[source_id]

        title = doc.metadata.get("title", "Unknown story")
        source = doc.metadata.get("source", "Not specified")

        sources.append(f"{title} — {source}")


    # 10. Format final answer
    answer = f"""
    **KRISHNA'S GUIDANCE**

    {response.guidance}

    ---

    **A STORY TO REFLECT UPON**

    **{response.story_title}**

    {response.story_explanation}

    **How it relates to your situation:**

    {response.practical_connection}

    ---

    **A FINAL REFLECTION**

    {response.reflection}
    """.strip()


    return {
        "answer": answer,
        "sources": sources
    }




if __name__ == "__main__":

    test_questions = [
        "I am confused about my responsibilities and what is right.",
        "I want to resolve a conflict peacefully.",
        "I feel jealous because my friends are more successful.",
        "I struggle with arrogance and want to become humble.",
        "How should I show kindness to someone who is different from me?"
    ]

    for question in test_questions:

        print("\n" + "=" * 60)
        print("USER DILEMMA:", question)
        print("=" * 60)

        result = get_krishna_response(question)

        print("\nKRISHNAAI RESPONSE:\n")
        print(result["answer"])

        print("\nKNOWLEDGE SOURCES:")
        for source in result["sources"]:
            print("-", source)
